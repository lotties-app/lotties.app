import { existsSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { DARK_MANIFEST, LIGHT_MANIFEST } from '../../pwa-manifest';
import { DARK, LIGHT } from '../theme/tokens';

const publicDir = resolve(__dirname, '..', '..', 'public');

describe('web manifests', () => {
  it('describe the same app: only icons and colours differ', () => {
    const {
      icons: lightIcons,
      theme_color: lt,
      background_color: lb,
      ...lightRest
    } = LIGHT_MANIFEST;
    const { icons: darkIcons, theme_color: dt, background_color: db, ...darkRest } = DARK_MANIFEST;
    expect(darkRest).toEqual(lightRest);
    expect(lightRest).toMatchObject({ id: '/', start_url: '/', scope: '/', name: 'Lotties' });
    expect(darkIcons).not.toEqual(lightIcons);
    expect([lt, lb]).toEqual([LIGHT.themeColor, LIGHT.background]);
    expect([dt, db]).toEqual([DARK.themeColor, DARK.background]);
  });

  it('give the dark manifest the dark icon set, sharing only the monochrome icon', () => {
    const srcs = (m: typeof DARK_MANIFEST, purpose: string) =>
      m.icons.filter((i) => i.purpose === purpose).map((i) => i.src);
    expect(srcs(DARK_MANIFEST, 'any')).toEqual(['/icon-dark-192.png', '/icon-dark-512.png']);
    expect(srcs(DARK_MANIFEST, 'maskable')).toEqual(['/icon-maskable-dark-512.png']);
    expect(srcs(LIGHT_MANIFEST, 'any')).toEqual(['/icon-192.png', '/icon-512.png']);
    expect(srcs(DARK_MANIFEST, 'monochrome')).toEqual(srcs(LIGHT_MANIFEST, 'monochrome'));
  });

  it.each([
    ['light', LIGHT_MANIFEST],
    ['dark', DARK_MANIFEST],
  ])('%s: every icon exists in web/public with the declared size', (_name, manifest) => {
    for (const icon of manifest.icons) {
      const file = resolve(publicDir, icon.src.slice(1));
      expect(existsSync(file), icon.src).toBe(true);
      const png = readFileSync(file);
      const [w, h] = icon.sizes.split('x').map(Number);
      expect([png.readUInt32BE(16), png.readUInt32BE(20)], icon.src).toEqual([w, h]);
    }
  });

  it('ships every file index.html and the scheme links point at', () => {
    const html = readFileSync(resolve(publicDir, '..', 'index.html'), 'utf8');
    const hrefs = [...html.matchAll(/<link[^>]*?href="(\/[^"]+)"/gs)].map((m) => m[1]);
    for (const href of [...hrefs, '/apple-touch-icon-dark.png', '/favicon-dark.ico']) {
      if (href.endsWith('.webmanifest')) continue; // generated by the build
      expect(existsSync(resolve(publicDir, href.slice(1))), href).toBe(true);
    }
  });
});
