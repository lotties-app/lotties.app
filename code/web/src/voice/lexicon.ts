import type { SpeechLocale } from './numberWords';
import { BREAST_MILK, CLOCK, FORMULA } from './tokens';

/*
 * The words of the v1 hands-free commands (docs/design/49-hands-free.md section 1), per language, after
 * normalization (lower case, no accents: "cocô" is "coco"). Grouped by role, not by phrase: the parser
 * combines roles (a stop verb and a nursing word is "stop nursing"), so phrasings the tests never saw
 * still parse, and a word that only means something next to another ("molhada" needs "fralda", a side
 * needs a breast word) is listed apart. Markers of negation, questions, other times, intentions, habits
 * and hedges make an utterance a non-command: nothing is logged from "não dormiu" or "she will sleep".
 */

export type VolumeUnit = 'ml' | 'oz' | 'l';
type Seq = readonly string[];

export interface Lexicon {
  /** Words skipped when deciding whether an utterance is only a side or only "stop". */
  fillers: ReadonlySet<string>;
  negation: ReadonlySet<string>;
  /** Other times, intentions, habits, hedges, durations: a report or a plan, not an event now. */
  report: ReadonlySet<string>;
  reportSeqs: readonly Seq[];
  /** How a sleep went ("dormiu bem"): a comment about the past. */
  quality: ReadonlySet<string>;
  /** Question words anywhere in the utterance. */
  questionWords: ReadonlySet<string>;
  questionSeqs: readonly Seq[];
  /** Words that make a question when they open the utterance (English auxiliaries). */
  questionOpeners: ReadonlySet<string>;
  /** Days other than today: a question about them is not "today". */
  otherDays: ReadonlySet<string>;
  otherDaySeqs: readonly Seq[];
  /** "how much": the milk-today question. */
  amountQuestion: readonly Seq[];
  /** "how long (since)": with a feed word, the last-feed question. */
  sinceQuestion: readonly Seq[];
  /** What the milk-today question may ask about. */
  milkTopic: ReadonlySet<string>;
  /** "última" / "last". */
  last: ReadonlySet<string>;
  /** What the last-feed question may ask about. */
  feedTopic: ReadonlySet<string>;
  /** "quando" / "when". */
  when: ReadonlySet<string>;
  bottle: ReadonlySet<string>;
  milk: ReadonlySet<string>;
  /** Verbs that log a bottle when an amount is said ("tomou 120"). */
  drink: ReadonlySet<string>;
  volumeUnits: Readonly<Record<string, VolumeUnit>>;
  /** Units of time: a number with one is a time or a duration. */
  timeUnits: ReadonlySet<string>;
  /** Words that mean the breast (nursing for sure). */
  breast: ReadonlySet<string>;
  /** Feed words that need a start or stop verb or a side ("mamar", "feeding"). */
  feed: ReadonlySet<string>;
  /** Past feed verbs: a feed that already happened, not a nursing to start. */
  pastFeed: ReadonlySet<string>;
  start: ReadonlySet<string>;
  stop: ReadonlySet<string>;
  /** Stop verbs that are also prepositions ("para"): they count only right before a feed word. */
  weakStop: ReadonlySet<string>;
  /** Utterances that are only "stop" (then the running timer decides). */
  bareStop: ReadonlySet<string>;
  nursingStopSeqs: readonly Seq[];
  left: ReadonlySet<string>;
  right: ReadonlySet<string>;
  sideNouns: ReadonlySet<string>;
  sleepStart: ReadonlySet<string>;
  sleepStartSeqs: readonly Seq[];
  sleepEnd: ReadonlySet<string>;
  sleepEndSeqs: readonly Seq[];
  /** Sleep nouns and the verb, for "começou a soneca", "nap over". */
  sleepObjects: ReadonlySet<string>;
  diaper: ReadonlySet<string>;
  wet: ReadonlySet<string>;
  /** "molhada": wet only next to a diaper word. */
  wetWithDiaper: ReadonlySet<string>;
  dirty: ReadonlySet<string>;
  dirtyWithDiaper: ReadonlySet<string>;
  bothWithDiaper: ReadonlySet<string>;
}

const set = (...words: string[]): ReadonlySet<string> => new Set(words);

