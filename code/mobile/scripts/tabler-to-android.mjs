// Converts the widget's Tabler icons (the iOS asset catalog, code/mobile/ios/App/LottiesWidgets/Assets.xcassets) into
// Android vector drawables for the home-screen widgets: res/drawable/ic_tabler_<name>.xml (docs/design/37-widgets-siri.md
// section 13). The icons are stroke-only paths (24x24, stroke 1.5, round caps and joins); the widget tints them.
// Run from code/mobile: node scripts/tabler-to-android.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const catalog = join(here, '..', 'ios', 'App', 'LottiesWidgets', 'Assets.xcassets');
const out = join(here, '..', 'android', 'app', 'src', 'main', 'res', 'drawable');

// In the iOS catalog but drawn by no Android widget.
const unused = new Set(['tabler-bed.imageset', 'tabler-plus.imageset']);

for (const set of readdirSync(catalog).filter(
  (name) => name.startsWith('tabler-') && name.endsWith('.imageset') && !unused.has(name),
)) {
  const folder = join(catalog, set);
  const svgFile = readdirSync(folder).find((name) => name.endsWith('.svg'));
  if (!svgFile) continue;
  const svg = readFileSync(join(folder, svgFile), 'utf8');
  const paths = [...svg.matchAll(/<path\s+([^>]*?)\/?>/g)]
    .map((match) => match[1])
    .filter((attributes) => !/stroke="none"/.test(attributes))
    .map((attributes) => /\bd="([^"]+)"/.exec(attributes)?.[1])
    .filter(Boolean);
  if (paths.length === 0) throw new Error(`${set}: no path`);
  const name = set.replace(/\.imageset$/, '').replace(/^tabler-/, '').replace(/-/g, '_');
  const body = paths
    .map(
      (d) => `    <path
        android:pathData="${d}"
        android:strokeColor="#FF000000"
        android:strokeWidth="1.5"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />`,
    )
    .join('\n');
  const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Tabler icon "${set.replace(/\.imageset$/, '').replace(/^tabler-/, '')}" (MIT), generated by code/mobile/scripts/tabler-to-android.mjs; do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
${body}
</vector>
`;
  writeFileSync(join(out, `ic_tabler_${name}.xml`), xml);
  console.log(`ic_tabler_${name}.xml`);
}
